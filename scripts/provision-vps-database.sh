#!/usr/bin/env bash
# Fresh VPS database provisioning for AffiliateOS.
# Run once from the repository root after `npm ci` and after creating the
# unprivileged Linux service account/group `affiliateos`.
#
# This script intentionally refuses existing database accounts, app/shadow tables,
# or a root .env file. It is for a fresh install, not password rotation/upgrades.
set -euo pipefail
umask 077

if [[ ! -f package.json || ! -f packages/database/prisma.config.ts || ! -x node_modules/.bin/prisma ]]; then
  echo "Run this from the AffiliateOS repository root after npm ci." >&2
  exit 1
fi

if [[ -e .env ]]; then
  echo "Refusing to overwrite existing .env. Back it up and review existing credentials first." >&2
  exit 1
fi

if ! getent group affiliateos >/dev/null; then
  echo "Linux group 'affiliateos' is missing. Create the service account/group first." >&2
  exit 1
fi

if ! command -v sudo >/dev/null || ! command -v openssl >/dev/null; then
  echo "This script requires sudo and openssl." >&2
  exit 1
fi

if [[ -n "${MYSQL_LOGIN_PATH:-}" ]] && command -v mysql >/dev/null; then
  db_client="$(command -v mysql)"
else
  db_client="$(command -v mariadb || command -v mysql || true)"
fi
if [[ -z "${db_client}" ]]; then
  echo "MariaDB/MySQL client not found. Install the client package for your database server." >&2
  exit 1
fi

db_admin() {
  if [[ "${db_client##*/}" == "mysql" && -n "${MYSQL_LOGIN_PATH:-}" ]]; then
    sudo "${db_client}" --login-path="${MYSQL_LOGIN_PATH}" "$@"
  else
    sudo "${db_client}" "$@"
  fi
}

# 32 random bytes rendered as hex plus a URL-safe suffix to satisfy MySQL's
# common MEDIUM password policy (lower/upper/digit/special character classes).
# The suffix is outside the random component's 256-bit entropy and needs no URL
# encoding; it also contains no SQL quote or shell expansion character.
app_password="$(openssl rand -hex 32)Aa7-"
migrate_password="$(openssl rand -hex 32)Aa7-"
shadow_password="$(openssl rand -hex 32)Aa7-"

existing_accounts="$(db_admin --batch --skip-column-names -e \
  "SELECT COUNT(*) FROM mysql.user WHERE User IN ('affiliateos_app','affiliateos_migrate','affiliateos_shadow')")"
if [[ "${existing_accounts}" != "0" ]]; then
  echo "Refusing: at least one AffiliateOS database account already exists." >&2
  exit 1
fi

existing_tables="$(db_admin --batch --skip-column-names -e \
  "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema='affiliateos' AND table_type='BASE TABLE'")"
if [[ "${existing_tables}" != "0" ]]; then
  echo "Refusing: affiliateos already contains tables. This script is only for a fresh database." >&2
  exit 1
fi

existing_shadow_tables="$(db_admin --batch --skip-column-names -e \
  "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema='affiliateos_shadow' AND table_type='BASE TABLE'")"
if [[ "${existing_shadow_tables}" != "0" ]]; then
  echo "Refusing: affiliateos_shadow already contains tables. Use a fresh shadow schema." >&2
  exit 1
fi

cat > .env <<EOF
# Generated by scripts/provision-vps-database.sh. Keep mode 600; never commit.
DATABASE_URL="mysql://affiliateos_app:${app_password}@127.0.0.1:3306/affiliateos?allowPublicKeyRetrieval=true"
MIGRATE_DATABASE_URL="mysql://affiliateos_migrate:${migrate_password}@127.0.0.1:3306/affiliateos"
SHADOW_DATABASE_URL="mysql://affiliateos_shadow:${shadow_password}@127.0.0.1:3306/affiliateos_shadow"
TRUST_PROXY=true
EOF
chmod 600 .env

# MariaDB root via local socket. On this host, TCP to 127.0.0.1 authenticates
# against the matching localhost account; verify with SELECT CURRENT_USER().
db_admin <<SQL
CREATE DATABASE IF NOT EXISTS affiliateos CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS affiliateos_shadow CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE USER 'affiliateos_app'@'localhost' IDENTIFIED BY '${app_password}';
CREATE USER 'affiliateos_migrate'@'localhost' IDENTIFIED BY '${migrate_password}';
CREATE USER 'affiliateos_shadow'@'localhost' IDENTIFIED BY '${shadow_password}';

GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, DROP, INDEX, REFERENCES
  ON affiliateos.* TO 'affiliateos_migrate'@'localhost';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, DROP, INDEX, REFERENCES
  ON affiliateos_shadow.* TO 'affiliateos_shadow'@'localhost';
SQL

# Apply checked-in migrations with the dedicated DDL account.
npm run prisma:deploy
npm run prisma:status

# Grant runtime access per existing table. Five history/audit tables are
# insert/select only; Prisma's _prisma_migrations table is excluded.
grant_sql="$(db_admin --batch --skip-column-names -e "
  SELECT CONCAT('GRANT SELECT, INSERT ON affiliateos.', table_name,
    ' TO ''affiliateos_app''@''localhost'';')
  FROM information_schema.tables
  WHERE table_schema='affiliateos' AND table_type='BASE TABLE'
    AND table_name IN ('audit_logs','creator_activities','creator_status_histories',
                       'campaign_contents','campaign_status_histories')
  UNION ALL
  SELECT CONCAT('GRANT SELECT, INSERT, UPDATE, DELETE ON affiliateos.', table_name,
    ' TO ''affiliateos_app''@''localhost'';')
  FROM information_schema.tables
  WHERE table_schema='affiliateos' AND table_type='BASE TABLE'
    AND table_name NOT IN ('_prisma_migrations','audit_logs','creator_activities',
                           'creator_status_histories','campaign_contents','campaign_status_histories')
  ORDER BY 1;
")"
if [[ -z "${grant_sql}" ]]; then
  echo "No AffiliateOS tables found after migration; runtime grants were not applied." >&2
  exit 1
fi
printf '%s\n' "${grant_sql}" | db_admin

# Build generated Prisma/package outputs before seeding the global permission list.
npm run build
node packages/database/dist/src/scripts/seed-rbac.js

# Runtime service receives only the runtime DSN; migration and shadow secrets stay
# in the deploy-only root .env and are not exposed to the web process.
sudo install -d -o root -g affiliateos -m 750 /etc/affiliateos
printf 'DATABASE_URL="%s"\nTRUST_PROXY=true\n' \
  "mysql://affiliateos_app:${app_password}@127.0.0.1:3306/affiliateos?allowPublicKeyRetrieval=true" \
  | sudo tee /etc/affiliateos/web.env >/dev/null
sudo chown root:affiliateos /etc/affiliateos/web.env
sudo chmod 640 /etc/affiliateos/web.env

echo "AffiliateOS DB provisioning, migrations, grants, build, and permission seed succeeded."
echo "Deploy-only URLs are in .env (mode 600); runtime env is /etc/affiliateos/web.env (no migration credentials)."
echo "Review systemd/HTTPS setup in README.md. No passwords were printed."
